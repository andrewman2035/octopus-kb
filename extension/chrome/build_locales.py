"""Builds what the extension's words come from (P25), from the two hand-written catalogs:

    python3 extension/chrome/build_locales.py   (uv run, or any Python with opencc-python-reimplemented)

- _locales/zh_TW/messages.json: _locales/zh_CN converted to traditional characters (OpenCC s2tw);
- messages.js: all three catalogs as one script, so the popup and options page can show the language chosen in the
  extension's settings (chrome.i18n only knows the browser's) and never a blank label when Chrome still holds the
  _locales of an older version (it reads them only when the extension is loaded).
The manifest's own words (__MSG_…__) still come from _locales through Chrome."""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LOCALES = ("en", "zh_CN", "zh_TW")


def traditional(messages: dict) -> dict:
    from opencc import OpenCC

    convert = OpenCC("s2tw").convert
    return {name: {**m, "message": convert(m["message"])} for name, m in messages.items()}


def catalogs() -> dict[str, dict]:
    read = {lang: json.loads((HERE / "_locales" / lang / "messages.json").read_text(encoding="utf-8"))
            for lang in ("en", "zh_CN")}
    return {**read, "zh_TW": traditional(read["zh_CN"])}


def messages_js(all_messages: dict[str, dict]) -> str:
    body = json.dumps(all_messages, ensure_ascii=False, indent=1, sort_keys=True)
    return ("// Generated by build_locales.py from _locales/*/messages.json: do not edit by hand.\n"
            f"const MESSAGES = {body};\n")


def main() -> int:
    found = catalogs()
    zh_tw = HERE / "_locales" / "zh_TW" / "messages.json"
    zh_tw.parent.mkdir(exist_ok=True)
    zh_tw.write_text(json.dumps(found["zh_TW"], ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (HERE / "messages.js").write_text(messages_js(found), encoding="utf-8")
    print(f"written: {zh_tw} and {HERE / 'messages.js'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
